/** A bottom sheet on the native <dialog>: focus moves in, Esc and the backdrop close it, focus returns on close. */
export function Sheet({ open, onClose, title, children }: { open: boolean; onClose: () => void; title: string; children: ReactNode }) {
  const ref = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (open && !d.open) d.showModal();
    if (!open && d.open) d.close();
  }, [open]);
  return (
    <dialog
      ref={ref}
      className={s.sheet}
      aria-label={title}
      onClose={onClose}
      onClick={(e) => {
        if (e.target === ref.current) onClose();
      }}
    >
      <div className={s.sheetInner}>
        <span className={s.grabber} aria-hidden />
        <div className={s.sheetHead}>
          <h2 className={s.sheetTitle}>{title}</h2>
          <button type="button" className={s.iconBtn} onClick={onClose} aria-label="Close">
            <Icon name="close" />
          </button>
        </div>
        {open && children}
      </div>
    </dialog>
  );
}

